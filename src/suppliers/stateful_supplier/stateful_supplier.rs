/// Generates owned values without input while allowing each call to update
/// internal state.
///
/// Implementations are suitable for counters, sequences, and generators that
/// behave like `FnMut() -> T`. Closures with that signature implement this
/// trait automatically.
///
/// # Examples
///
/// ```
/// use qubit_function::{BoxStatefulSupplier, StatefulSupplier};
///
/// let mut counter = 0;
/// let mut supplier = BoxStatefulSupplier::new(move || {
///     counter += 1;
///     counter
/// });
///
/// assert_eq!(supplier.get(), 1);
/// assert_eq!(supplier.get(), 2);
/// ```
///
/// # Type Parameters
///
/// - `T`: The owned value generated by each call to [`get`](Self::get).
pub trait StatefulSupplier<T> {
    /// Calls the supplier and returns its next generated value.
    ///
    /// The mutable receiver allows implementations to advance counters,
    /// consume sequences, or otherwise update state between calls.
    ///
    /// # Returns
    ///
    /// The next generated value of type `T`.
    ///
    /// # Examples
    ///
    /// ```
    /// use qubit_function::{BoxStatefulSupplier, StatefulSupplier};
    ///
    /// let mut supplier = BoxStatefulSupplier::new(|| 42);
    /// assert_eq!(supplier.get(), 42);
    /// ```
    #[must_use = "the supplied value should be used"]
    fn get(&mut self) -> T;
}

crate::macros::impl_closure_trait!(StatefulSupplier<T>, get, FnMut() -> T);
